window.getSaloneSVG = function(icon, size = 24, strokeWidth = 2) {
  if (!icon) return '';
  if (icon.rawSvg) {
    return icon.rawSvg.replace(/width="[^"]*"/, `width="${size}"`).replace(/height="[^"]*"/, `height="${size}"`);
  }
  if (icon.type === 'fill') {
    return `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="currentColor" xmlns="http://www.w3.org/2000/svg">${icon.svg}</svg>`;
  }
  if (icon.type === 'multi') {
    return `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg">${icon.svg}</svg>`;
  }
  return `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" xmlns="http://www.w3.org/2000/svg">${icon.svg}</svg>`;
};
